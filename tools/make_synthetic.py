"""Generate the synthetic files of the test corpus, and their sidecars.

Run from the repository root::

    python tools/make_synthetic.py

The numbers of every generated file come from the formulas below, and the expected
results written to the sidecars are computed here from those same numbers, never by
calling the readers. The corpus therefore checks the readers against an independent
source of truth.

Files copied from ``qclab-utilities`` (``tests/corpus/synthetic/*.txt`` and
``tests/corpus/theoretical/``) are not regenerated; only their sidecars are written,
with expectations taken from a plain line-by-line parse done here.
"""

from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
CORPUS = ROOT / "tests" / "corpus"
SYNTHETIC = CORPUS / "synthetic"
THEORETICAL = CORPUS / "theoretical"

CONFIRMED = {"confirmed": True, "by": "Rob", "date": "2026-11-17"}
WHO = {
    "program_or_instrument": "synthetic: generated by tools/make_synthetic.py",
    "version": "n/a",
    "molecule": "none (artificial bands)",
    "producer": "QCLab, graphing project",
}


def gaussian(x: float, centre: float, width: float, height: float) -> float:
    """Return a Gaussian band, used to make the artificial spectra."""
    return height * math.exp(-0.5 * ((x - centre) / width) ** 2)


def uvvis_rows() -> list[tuple[str, str, str, str, str]]:
    """Return (x, y1, y2, y3, y4) as text; x in nm, four absorbance columns."""
    rows = []
    for i in range(41):
        x = 300.0 + 5.0 * i
        base = gaussian(x, 350, 25, 0.8) + gaussian(x, 430, 20, 0.3)
        values = [base + 0.02, 0.5 * base + 0.01, 0.25 * base, 1.5 * base + 0.05]
        rows.append((f"{x:.1f}", *[f"{v:.4f}" for v in values]))
    return rows


def ir_rows() -> list[tuple[str, str]]:
    """Return (wavenumber, %T) from 4000 down to 400 cm-1, as an IR export does."""
    rows = []
    for i in range(901):
        x = 4000.0 - 4.0 * i
        t = 95.0 - gaussian(x, 1715, 15, 60) - gaussian(x, 3400, 120, 45)
        rows.append((f"{x:.1f}", f"{t:.3f}"))
    return rows


def plain(value: str) -> float:
    """Parse a number written with a point or a comma, the plain way."""
    return float(value.replace(",", "."))


def table_expect(rows: list[list[str]], header: list[str] | None) -> dict[str, Any]:
    """Expected table, computed from the text rows without using the readers."""
    numbers = [[plain(cell) for cell in row] for row in rows]
    return {
        "rows": len(numbers),
        "columns": len(numbers[0]),
        "first": numbers[0],
        "last": numbers[-1],
        "header": header,
    }


def mapping(
    x_quantity: str,
    x_unit: str,
    y_quantity: str,
    technique: str,
    y_columns: list[int] | None = None,
) -> dict[str, Any]:
    """Return a column mapping in the sidecar's spelling (enum member names)."""
    return {
        "x_column": 0,
        "y_columns": y_columns or [1],
        "x_quantity": x_quantity,
        "x_unit": x_unit,
        "y_quantity": y_quantity,
        "technique": technique,
        "origin": "EXPERIMENTAL",
    }


def write_sidecar(path: Path, **fields: Any) -> None:
    """Write ``<file>.corpus.json`` next to ``path``."""
    sidecar = {
        "schema": 1,
        "kind": "synthetic",
        "source": WHO,
        "publishable": CONFIRMED,
        **fields,
    }
    target = path.with_name(path.name + ".corpus.json")
    target.write_text(
        json.dumps(sidecar, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )


def write_text(
    path: Path, text: str, encoding: str = "utf-8", crlf: bool = False
) -> None:
    """Write text with the encoding and line ending chosen."""
    newline = "\r\n" if crlf else "\n"
    path.write_bytes(text.replace("\n", newline).encode(encoding))


def text_files() -> None:
    uv = uvvis_rows()
    ir = ir_rows()
    one = [[x, y] for x, y, *_ in uv]

    # 1. Spanish-language instrument export: ';' delimiter, decimal comma, cp1252, CRLF.
    head = ["Longitud de onda (nm)", "Absorbancia"]
    lines = [
        "Espectrofotómetro SintéticoSpec 100 (archivo sintético)",
        "Muestra: disolución de ejemplo",
        "Fecha: 17/11/2026",
        "",
        ";".join(head),
        *[f"{x.replace('.', ',')};{y.replace('.', ',')}" for x, y in one],
    ]
    path = SYNTHETIC / "uvvis-semicolon-comma-cp1252.csv"
    write_text(path, "\n".join(lines) + "\n", "cp1252", crlf=True)
    write_sidecar(
        path,
        reader="text",
        expect={
            "table": {
                **table_expect([list(r) for r in one], head),
                "delimiter": ";",
                "decimal": ",",
            },
            "spectra": {"count": 1, "names": ["Absorbancia"], "x_reordered": False},
        },
        mapping=mapping("WAVELENGTH", "NM", "ABSORBANCE", "UV_VIS"),
    )

    # 2. Tab-delimited text with a header and a point decimal.
    head = ["Wavelength (nm)", "Absorbance"]
    path = SYNTHETIC / "uvvis-tab-header.txt"
    write_text(path, "\n".join(["\t".join(head), *["\t".join(r) for r in one]]) + "\n")
    write_sidecar(
        path,
        reader="text",
        expect={
            "table": {
                **table_expect([list(r) for r in one], head),
                "delimiter": "\t",
                "decimal": ".",
            },
            "spectra": {"count": 1, "names": ["Absorbance"], "x_reordered": False},
        },
        mapping=mapping("WAVELENGTH", "NM", "ABSORBANCE", "UV_VIS"),
    )

    # 3. IR export, descending wavenumbers, percent transmittance.
    head = ["Wavenumber (cm-1)", "%T"]
    path = SYNTHETIC / "ir-descending-percentT.txt"
    write_text(
        path,
        "\n".join(
            ["# synthetic IR export", "\t".join(head), *["\t".join(r) for r in ir]]
        )
        + "\n",
    )
    write_sidecar(
        path,
        reader="text",
        expect={
            "table": table_expect([list(r) for r in ir], head),
            "spectra": {"count": 1, "names": ["%T"], "x_reordered": True},
        },
        mapping=mapping("WAVENUMBER", "CM1", "TRANSMITTANCE", "IR"),
    )

    # 4. Four absorbance columns sharing one x column.
    head = ["Wavelength", "Abs A", "Abs B", "Abs C", "Abs D"]
    path = SYNTHETIC / "uvvis-multicolumn.csv"
    write_text(path, "\n".join([",".join(head), *[",".join(r) for r in uv]]) + "\n")
    write_sidecar(
        path,
        reader="text",
        expect={
            "table": table_expect([list(r) for r in uv], head),
            "spectra": {"count": 4, "names": head[1:], "x_reordered": False},
        },
        mapping=mapping("WAVELENGTH", "NM", "ABSORBANCE", "UV_VIS", [1, 2, 3, 4]),
    )

    # 5. UTF-8 with byte-order mark, as Excel writes csv.
    head = ["Wavelength (nm)", "Absorbance"]
    path = SYNTHETIC / "uvvis-bom-utf8.csv"
    write_text(
        path,
        "\n".join([",".join(head), *[",".join(r) for r in one]]) + "\n",
        "utf-8-sig",
        crlf=True,
    )
    write_sidecar(
        path,
        reader="text",
        expect={
            "table": table_expect([list(r) for r in one], head),
            "spectra": {"count": 1, "names": ["Absorbance"], "x_reordered": False},
        },
        mapping=mapping("WAVELENGTH", "NM", "ABSORBANCE", "UV_VIS"),
    )


def sheet_files() -> None:
    from odf.opendocument import OpenDocumentSpreadsheet
    from odf.table import CoveredTableCell, Table, TableCell, TableRow
    from odf.text import P
    from openpyxl import Workbook

    uv = uvvis_rows()
    one = [(x, y) for x, y, *_ in uv]
    head = ["Wavelength (nm)", "Absorbance"]
    expect = {
        "table": table_expect([list(r) for r in one], head),
        "spectra": {"count": 1, "names": ["Absorbance"], "x_reordered": False},
    }
    chosen = mapping("WAVELENGTH", "NM", "ABSORBANCE", "UV_VIS")

    # Layout: one empty row, a note, a merged "Sample 7" label, the header, the data.
    workbook = Workbook()
    sheet = workbook.active
    assert sheet is not None
    sheet.append([])
    sheet.append(["Instrument: SynthSpec (synthetic)"])
    sheet.append(["Sample 7"])
    sheet.merge_cells("A3:B3")
    sheet.append(head)
    for x, y in one:
        sheet.append([float(x), float(y)])
    path = SYNTHETIC / "uvvis-merged-header.xlsx"
    workbook.save(path)
    write_sidecar(path, reader="sheet", expect=expect, mapping=chosen)

    document = OpenDocumentSpreadsheet()
    table = Table(name="Sheet1")

    def text_row(*cells: str) -> TableRow:
        row = TableRow()
        for text in cells:
            cell = TableCell(valuetype="string")
            cell.addElement(P(text=text))
            row.addElement(cell)
        return row

    table.addElement(TableRow())
    table.addElement(text_row("Instrument: SynthSpec (synthetic)"))
    merged_row = TableRow()
    merged = TableCell(valuetype="string", numbercolumnsspanned=2)
    merged.addElement(P(text="Sample 7"))
    merged_row.addElement(merged)
    merged_row.addElement(CoveredTableCell())
    table.addElement(merged_row)
    table.addElement(text_row(*head))
    for x, y in one:
        row = TableRow()
        for value in (x, y):
            row.addElement(TableCell(valuetype="float", value=float(value)))
        table.addElement(row)
    document.spreadsheet.addElement(table)
    path = SYNTHETIC / "uvvis-merged-header.ods"
    document.save(str(path))
    write_sidecar(path, reader="sheet", expect=expect, mapping=chosen)

    # Must fail: a workbook with no numbers.
    words = Workbook()
    sheet = words.active
    assert sheet is not None
    sheet.append(["a", "b"])
    sheet.append(["c", "d"])
    path = SYNTHETIC / "words-only.xlsx"
    words.save(path)
    write_sidecar(
        path,
        reader="sheet",
        expect={"error": {"stage": "load", "type": "NoNumericBlock"}},
    )


def failing_files() -> None:
    path = SYNTHETIC / "empty.txt"
    write_text(path, "")
    write_sidecar(
        path,
        reader="text",
        expect={"error": {"stage": "load", "type": "NoNumericBlock"}},
    )

    path = SYNTHETIC / "words-only.txt"
    write_text(path, "Sample report\nNo numbers here\nJust words, as a title page\n")
    write_sidecar(
        path,
        reader="text",
        expect={"error": {"stage": "load", "type": "NoNumericBlock"}},
    )

    # '1,5,2,5' is either four integers or two numbers with a decimal comma.
    path = SYNTHETIC / "ambiguous-commas.csv"
    write_text(path, "1,5,2,5\n2,5,3,5\n3,5,4,5\n")
    write_sidecar(
        path,
        reader="text",
        expect={"error": {"stage": "load", "type": "AmbiguousFormat"}},
    )

    # Loads fine, but the x column repeats a value, so no spectrum can be built.
    rows = [["300", "0.1"], ["310", "0.2"], ["310", "0.3"], ["320", "0.4"]]
    path = SYNTHETIC / "duplicate-x.csv"
    write_text(path, "Wavelength,Abs\n" + "\n".join(",".join(r) for r in rows) + "\n")
    write_sidecar(
        path,
        reader="text",
        expect={
            "table": table_expect(rows, ["Wavelength", "Abs"]),
            "error": {"stage": "map", "type": "InvalidMapping"},
        },
        mapping=mapping("WAVELENGTH", "NM", "ABSORBANCE", "UV_VIS"),
    )

    # A broken cell inside the table must be an error, never a silently shorter table.
    malformed = {
        "malformed-cell-typo.txt": ("\t", lambda i: "0.5x" if i == 49 else None),
        "overflow-marker.csv": (";", lambda i: "OVRFLW" if i == 10 else None),
        "missing-last-value.csv": (";", lambda i: "" if i == 99 else None),
    }
    for name, (delimiter, bad) in malformed.items():
        lines = []
        for i in range(100):
            value = bad(i)
            y = f"{i / 100:.2f}" if value is None else value
            lines.append(f"{300 + i}{delimiter}{y}")
        path = SYNTHETIC / name
        write_text(path, "\n".join(lines) + "\n")
        write_sidecar(
            path,
            reader="text",
            expect={"error": {"stage": "load", "type": "MalformedCell"}},
        )

    # The same defect in a spreadsheet: an empty cell in the middle of a column.
    from openpyxl import Workbook

    workbook = Workbook()
    sheet = workbook.active
    assert sheet is not None
    sheet.append(["Wavelength (nm)", "Absorbance"])
    for i in range(100):
        sheet.append([300.0 + i, None if i == 49 else i / 100])
    path = SYNTHETIC / "empty-cell.xlsx"
    workbook.save(path)
    write_sidecar(
        path,
        reader="sheet",
        expect={"error": {"stage": "load", "type": "MalformedCell"}},
    )


def copied_text_sidecars() -> None:
    """Sidecars of the copied qclab-utilities spectra (plain-parse expectations)."""
    specs = {
        "blue-dye.txt": ("WAVELENGTH", "NM", "MOLAR_ABSORPTIVITY", "UV_VIS", None),
        "green-dye.txt": ("WAVELENGTH", "NM", "MOLAR_ABSORPTIVITY", "UV_VIS", None),
        "yellow-dye.txt": ("WAVELENGTH", "NM", "MOLAR_ABSORPTIVITY", "UV_VIS", None),
        "emitter-export.txt": (
            "WAVELENGTH",
            "NM",
            "INTENSITY",
            "UV_VIS",
            ["wavelength_nm", "intensity_au"],
        ),
        # Wavelength in angstrom: no such unit in v1.0, so only the reading is checked.
        "literature-flat.txt": (
            None,
            None,
            None,
            None,
            ["Wavelength(A)", "Absorbance"],
        ),
    }
    for name, (xq, xu, yq, technique, header) in specs.items():
        path = SYNTHETIC / name
        rows = []
        for line in path.read_text(encoding="utf-8").splitlines():
            parts = line.split()
            if len(parts) == 2 and all(_is_float(p) for p in parts):
                rows.append(parts)
        expect: dict[str, Any] = {"table": table_expect(rows, header)}
        fields: dict[str, Any] = {"reader": "text", "expect": expect}
        if xq is not None:
            assert xu and yq and technique
            fields["mapping"] = mapping(xq, xu, yq, technique)
            expect["spectra"] = {
                "count": 1,
                "names": [header[1] if header else "Column 2"],
                "x_reordered": False,
            }
        source = {
            **WHO,
            "program_or_instrument": "synthetic: from qclab-utilities examples",
        }
        write_sidecar(path, source=source, **fields)


def _is_float(text: str) -> bool:
    try:
        float(text)
    except ValueError:
        return False
    return True


def theoretical_sidecars() -> None:
    """Sidecars of the artificial ORCA-style and Turbomole-style files."""
    source = {
        "program_or_instrument": "ORCA, artificial output, 4.2.1 layout (not real)",
        "version": "4.2.1 (layout only)",
        "molecule": "none (artificial transitions)",
        "producer": "QCLab, qclab-utilities examples",
    }
    for name in (
        "synthetic-3bands.out",
        "synthetic-shoulder.out",
        "synthetic-wave.out",
    ):
        path = THEORETICAL / name
        transitions = []
        for line in path.read_text(encoding="utf-8").splitlines():
            parts = line.split()
            if (
                len(parts) == 8
                and parts[0].isdigit()
                and all(_is_float(p) for p in parts)
            ):
                transitions.append([float(parts[1]), float(parts[2]), float(parts[3])])
        write_sidecar(
            path,
            source=source,
            reader="orca",
            expect={
                "transitions": len(transitions),
                "first": transitions[0],
                "last": transitions[-1],
                "columns": ["energy_cm1", "wavelength_nm", "fosc"],
            },
        )

    path = THEORETICAL / "imaginary-mode.vibspectrum"
    wavenumbers = []
    intensities = []
    active = 0
    for line in path.read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if parts and parts[0].isdigit():
            # Columns: mode, [symmetry], wave number, IR intensity, IR flag, Raman flag.
            wavenumbers.append(float(parts[-4]))
            intensities.append(float(parts[-3]))
            active += parts[-2] == "YES"
    write_sidecar(
        path,
        source={
            "program_or_instrument": "Turbomole, artificial vibspectrum (not real)",
            "version": "7.x layout only",
            "molecule": "none (artificial modes)",
            "producer": "QCLab, qclab-utilities examples",
        },
        reader="turbomole-vibspectrum",
        expect={
            "modes": len(wavenumbers),
            "ir_active_modes": active,
            "first": [wavenumbers[0], intensities[0]],
            "last": [wavenumbers[-1], intensities[-1]],
            "negative_wavenumbers": [w for w in wavenumbers if w < 0],
        },
    )


def orca_failing_files() -> None:
    """Artificial ORCA-style outputs that the parser must refuse, with the reason."""
    base = (THEORETICAL / "synthetic-3bands.out").read_text(encoding="utf-8")
    source = {
        "program_or_instrument": "ORCA, artificial output, 4.2.1 layout (not real)",
        "version": "4.2.1 (layout only)",
        "molecule": "none (artificial transitions)",
        "producer": "QCLab, graphing project (derived from synthetic-3bands.out)",
    }
    cases = {
        # The spectrum block is gone: the parser must name the block it did not find.
        "orca-style-no-block.out": (
            base.split("* O   R   C   A *")[0] + "no spectrum was requested\n",
            "MissingBlock",
        ),
        # A damaged number inside the block: an error, never a shorter spectrum.
        "orca-style-broken-row.out": (
            base.replace("25000.0    400.0", "25000.0x   400.0"),
            "MalformedBlock",
        ),
    }
    for name, (text, error) in cases.items():
        path = THEORETICAL / name
        assert text != base
        write_text(path, text)
        write_sidecar(
            path,
            source=source,
            reader="orca",
            expect={"error": {"stage": "parse", "type": error}},
        )


