def turbomole_files() -> None:
    """Artificial Turbomole-style outputs: one that reads and some that must not."""
    source = {
        "program_or_instrument": "Turbomole, artificial output, 7.x layout (not real)",
        "version": "7.x (layout only)",
        "molecule": "none (artificial states)",
        "producer": "QCLab, graphing project (layout of a real exspectrum header)",
    }
    rows = []
    for line in EXSPECTRUM_TEXT.splitlines():
        parts = line.split()
        if len(parts) == 8 and parts[0].isdigit():
            rows.append([float(parts[4]), float(parts[5]), float(parts[7])])
    path = THEORETICAL / "artificial.exspectrum"
    write_text(path, EXSPECTRUM_TEXT)
    write_sidecar(
        path,
        source=source,
        reader="turbomole-exspectrum",
        expect={"transitions": len(rows), "first": rows[0], "last": rows[-1]},
    )

    vib = (THEORETICAL / "imaginary-mode.vibspectrum").read_text(encoding="utf-8")
    cases = {
        # A damaged number inside the table: an error, never a shorter table.
        "broken-row.vibspectrum": (vib.replace("612.30", "612.3x"), "MalformedBlock"),
        # No "$end": the file was cut, and nothing says how many modes are missing.
        "truncated.vibspectrum": (vib.replace("$end\n", ""), "MalformedBlock"),
        "broken-row.exspectrum": (
            EXSPECTRUM_TEXT.replace("25000.000", "25000.00x"),
            "MalformedBlock",
        ),
        "no-header.exspectrum": (
            "\n".join(
                line
                for line in EXSPECTRUM_TEXT.splitlines()
                if not line.startswith("#")
            )
            + "\n",
            "MissingBlock",
        ),
    }
    for name, (text, error) in cases.items():
        path = THEORETICAL / name
        assert text != vib and text != EXSPECTRUM_TEXT
        write_text(path, text)
        reader = (
            "turbomole-vibspectrum"
            if name.endswith("vibspectrum")
            else "turbomole-exspectrum"
        )
        write_sidecar(
            path,
            source=source,
            reader=reader,
            expect={"error": {"stage": "parse", "type": error}},
        )


def main() -> None:
    SYNTHETIC.mkdir(parents=True, exist_ok=True)
    text_files()
    sheet_files()
    failing_files()
    copied_text_sidecars()
    theoretical_sidecars()
    orca_failing_files()
    turbomole_files()
    print("Synthetic corpus files and sidecars written to", CORPUS)


if __name__ == "__main__":
    main()
